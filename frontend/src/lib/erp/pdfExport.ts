import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { appInfo } from "./appInfo";
import { nf } from "./format";
import type { PlannerFgpnItem } from "@/components/erp/SimulationFgpnPlanner";

export interface SimulationExportData {
  ref: string;
  projectName: string;
  projectId: string;
  engineerName: string;
  engineerUsername: string;
  runAt: string;
  mode: string;
  safetyCoefficient: number;
  includeInTransit: boolean;
  targetDate?: string;
  bomVersion?: string;
  bomFileName?: string;
  feasibility: string;
  totalPlannedOutput: number;
  plannerItems: PlannerFgpnItem[];
  materialBreakdown: {
    partNumber: string;
    description: string;
    bomUsage: number;
    required: number;
    practical: number;
    transit: number;
    wip: number;
    available: number;
    shortfall: number;
    unit: string;
  }[];
}

export function exportSimulationToPdf(data: SimulationExportData) {
  const doc = new jsPDF({
    orientation: "portrait",
    unit: "mm",
    format: "a4",
  });

  const primaryColor: [number, number, number] = [33, 43, 54];
  const accentColor: [number, number, number] = [217, 119, 6];
  const dangerColor: [number, number, number] = [239, 68, 68];

  // Header band
  doc.setFillColor(...primaryColor);
  doc.rect(0, 0, 210, 22, "F");

  doc.setFont("helvetica", "bold");
  doc.setFontSize(14);
  doc.setTextColor(255, 255, 255);
  doc.text(appInfo.productName.toUpperCase(), 14, 11);

  doc.setFont("helvetica", "normal");
  doc.setFontSize(9);
  doc.setTextColor(203, 213, 225);
  doc.text("MATERIAL FEASIBILITY SIMULATION REPORT", 14, 17);

  doc.setFont("helvetica", "bold");
  doc.setFontSize(10);
  doc.setTextColor(255, 255, 255);
  doc.text(data.ref, 196, 14, { align: "right" });

  let y = 30;

  // Key Parameters Grid / Summary Panel
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text("1. Simulation Parameters & Context", 14, y);
  y += 5;

  autoTable(doc, {
    startY: y,
    head: [["Parameter", "Value", "Parameter", "Value"]],
    body: [
      [
        "Project",
        `${data.projectName} (${data.projectId})`,
        "Generated By",
        `${data.engineerName} (@${data.engineerUsername})`,
      ],
      ["Simulation Mode", data.mode, "Timestamp", new Date(data.runAt).toLocaleString()],
      [
        "Safety Coefficient",
        `x${data.safetyCoefficient}`,
        "Active BOM Version",
        data.bomVersion ? `v${data.bomVersion} (${data.bomFileName || ""})` : "N/A",
      ],
      [
        "In-Transit Stock",
        data.includeInTransit ? "Included in Calculation" : "Excluded (Practical stock only)",
        "Target Date",
        data.targetDate || "N/A",
      ],
      [
        "Overall Feasibility",
        data.feasibility,
        "Total Planned Output",
        `${nf.format(data.totalPlannedOutput)} pcs`,
      ],
    ],
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 65, 85],
    },
    styles: {
      cellPadding: 2,
    },
    margin: { left: 14, right: 14 },
  });

  const finalParamY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable
    .finalY;
  y = finalParamY + 10;

  // Table 2: Prioritized FGPNs & Quantities
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text("2. Prioritized Finished Goods Part Numbers (FGPN)", 14, y);
  y += 5;

  const fgpnRows = data.plannerItems.map((item, idx) => [
    `#${idx + 1}`,
    item.poNumber,
    item.fgpn,
    item.description || "—",
    nf.format(item.defaultQty),
    nf.format(item.simQty),
    item.launchableQty !== undefined ? nf.format(item.launchableQty) : "—",
    item.coveragePercent !== undefined ? `${item.coveragePercent}%` : "—",
  ]);

  autoTable(doc, {
    startY: y,
    head: [
      [
        "Priority",
        "PO Number",
        "FGPN",
        "Description",
        "PO Balance",
        "Sim Qty",
        "Launchable",
        "Coverage",
      ],
    ],
    body: fgpnRows,
    theme: "striped",
    headStyles: {
      fillColor: accentColor,
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 65, 85],
    },
    columnStyles: {
      0: { halign: "center", fontStyle: "bold" },
      4: { halign: "right" },
      5: { halign: "right", fontStyle: "bold" },
      6: { halign: "right" },
      7: { halign: "center" },
    },
    styles: {
      cellPadding: 2,
    },
    margin: { left: 14, right: 14 },
  });

  const finalFgpnY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY;
  y = finalFgpnY + 10;

  // Table 3: Material Requirements Breakdown
  doc.setFont("helvetica", "bold");
  doc.setFontSize(11);
  doc.setTextColor(30, 41, 59);
  doc.text("3. Raw Material Requirements & Availability Breakdown", 14, y);
  y += 5;

  const materialRows = data.materialBreakdown.map((r) => [
    r.partNumber,
    r.description,
    `${nf.format(Math.round(r.required))} ${r.unit}`,
    nf.format(r.practical),
    data.includeInTransit ? nf.format(r.transit) : "—",
    nf.format(r.wip),
    r.shortfall > 0 ? nf.format(Math.round(r.shortfall)) : "0",
    r.shortfall > 0 ? "SHORTFALL" : "COVERED",
  ]);

  autoTable(doc, {
    startY: y,
    head: [
      [
        "Material Part",
        "Description",
        "Total Demand",
        "Warehouse",
        "In-Transit",
        "CutMan WIP",
        "Shortfall",
        "Status",
      ],
    ],
    body: materialRows,
    theme: "grid",
    headStyles: {
      fillColor: primaryColor,
      textColor: [255, 255, 255],
      fontSize: 8,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [51, 65, 85],
    },
    columnStyles: {
      0: { fontStyle: "bold" },
      2: { halign: "right", fontStyle: "bold" },
      3: { halign: "right" },
      4: { halign: "right" },
      5: { halign: "right" },
      6: { halign: "right" },
      7: { halign: "center", fontStyle: "bold" },
    },
    didParseCell: (hookData) => {
      if (hookData.section === "body") {
        const row = data.materialBreakdown[hookData.row.index];
        if (row && row.shortfall > 0) {
          if (hookData.column.index === 6 || hookData.column.index === 7) {
            hookData.cell.styles.textColor = dangerColor;
          }
        }
      }
    },
    styles: {
      cellPadding: 2,
    },
    margin: { left: 14, right: 14 },
  });

  // Footer page numbering
  const pageCount = (
    doc as unknown as { internal: { getNumberOfPages: () => number } }
  ).internal.getNumberOfPages();
  for (let i = 1; i <= pageCount; i++) {
    doc.setPage(i);
    doc.setFontSize(7);
    doc.setTextColor(148, 163, 184);
    doc.text(
      `Generated by ${appInfo.productName} | Engineer: ${data.engineerName} (${data.engineerUsername}) | Page ${i} of ${pageCount}`,
      105,
      290,
      { align: "center" },
    );
  }

  doc.save(`${data.ref}_Feasibility_Report.pdf`);
}
