export function resolveProjectId(identifier?: string | number | null): string | undefined {
  if (identifier === null || identifier === undefined) return undefined;
  const raw = String(identifier).trim();
  if (!raw) return undefined;

  const normalized = raw.includes(" · ")
    ? raw.split(" · ")[0]
    : raw.includes(" - ")
      ? raw.split(" - ")[0]
      : raw;

  return projects.find((p) => p.id === normalized || p.code === normalized)?.id;
}

export const findProject = (identifier: string | number) => {
  const resolvedId = resolveProjectId(identifier);
  return projects.find((p) => p.id === resolvedId);
};

export const projectLabel = (identifier: string | number) => {
  const p = findProject(identifier);
  if (p) return `${p.code} · ${p.name}`;
  return String(identifier);
};
export const findMaterial = (partNumber: string) =>
  materials.find((m) => m.partNumber === partNumber);
export const findPo = (id: string) => purchaseOrders.find((p) => p.id === id);
export const findUserByUsername = (username: string) => users.find((u) => u.username === username);

export const poQty = (po: { lines: { quantity: number }[] }) =>
  po.lines.reduce((s, l) => s + l.quantity, 0);
export const poDelivered = (po: { lines: { deliveredQuantity: number }[] }) =>
  po.lines.reduce((s, l) => s + l.deliveredQuantity, 0);
export const poRemaining = (po: { lines: { quantity: number; deliveredQuantity: number }[] }) =>
  po.lines.reduce((s, l) => s + (l.quantity - l.deliveredQuantity), 0);
export const poAmount = (po: {
  lines: { quantity: number; deliveredQuantity: number; unitPrice: number }[];
}) => po.lines.reduce((s, l) => s + (l.quantity - l.deliveredQuantity) * l.unitPrice, 0);

export const theoreticalStock = (m: Material) => m.practicalStock + m.transitStock;
export const isBelowThreshold = (m: Material) =>
  m.status === "Active" && m.practicalStock <= m.criticalThreshold;
